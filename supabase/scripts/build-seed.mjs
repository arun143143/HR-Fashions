// Builds supabase/seed.sql from the content files the site uses today (Frontend/src/data),
// so the database starts with exactly what the site shows. Run from the repo root:
//     node supabase/scripts/build-seed.mjs
// Everything it writes is placeholder content until the owner confirms it.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { serviceList } from '../../Frontend/src/data/services.js';
import { designList } from '../../Frontend/src/data/designs.js';
import { generalFaqs } from '../../Frontend/src/data/faqs.js';
import { site } from '../../Frontend/src/data/site.js';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (list) => `array[${list.map(q).join(', ')}]::text[]`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

const out = [];
out.push('-- GENERATED by supabase/scripts/build-seed.mjs from Frontend/src/data. Do not edit by hand.');
out.push('-- PLACEHOLDER CONTENT: prices, claims, contact details and Unsplash photos must be confirmed by the owner.');
out.push('-- Safe to run more than once: it empties the content tables first. It never touches bookings or profiles.');
out.push('');
out.push('begin;');
out.push('truncate public.service_prices, public.faqs, public.services, public.designs, public.banners, public.settings restart identity cascade;');
out.push('');

out.push('-- Services, their prices and their questions');
let serviceFaqCount = 0;
serviceList.forEach((s, i) => {
    out.push(
        `insert into public.services (slug, name, title, description, hero_image, features, types, tips, sort_order) values (` +
            [q(s.slug), q(s.name), q(s.title), q(s.description), q(s.heroImg), arr(s.features ?? []), json(s.types ?? []), json(s.tips ?? []), i + 1].join(', ') +
            ');',
    );
    (s.pricing ?? []).forEach((p, j) => {
        out.push(
            `insert into public.service_prices (service_id, label, price_text, sort_order) select id, ${q(p.type)}, ${q(p.price)}, ${j + 1} from public.services where slug = ${q(s.slug)};`,
        );
    });
    (s.faqs ?? []).forEach((f, j) => {
        serviceFaqCount += 1;
        out.push(
            `insert into public.faqs (service_id, question, answer, sort_order) select id, ${q(f.question)}, ${q(f.answer)}, ${j + 1} from public.services where slug = ${q(s.slug)};`,
        );
    });
});
out.push('');

out.push('-- General questions (home page)');
generalFaqs.forEach((f, i) => {
    out.push(`insert into public.faqs (service_id, question, answer, sort_order) values (null, ${q(f.question)}, ${q(f.answer)}, ${i + 1});`);
});
out.push('');

out.push('-- Gallery');
designList.forEach((d) => {
    out.push(`insert into public.designs (title, category, image_path, sort_order, active) values (${q(d.title)}, ${q(d.category)}, ${q(d.image)}, ${d.sortOrder}, ${d.active});`);
});
out.push('');

out.push('-- Hero banner');
out.push(`insert into public.banners (kind, text, image_path, sort_order) values ('hero', 'Clothes stitched to your measure.', ${q(site.heroImage)}, 1);`);
out.push('');

out.push('-- Shop settings (all public; contact details are placeholders)');
const settings = {
    shop_name: site.name,
    tagline: site.tagline,
    phone: site.phone,
    whatsapp_number: site.whatsappNumber,
    email: site.email,
    address: site.address,
    shop_hours: site.hours ?? '',
    delivery_note: site.deliveryNote,
    announcement: '',
};
Object.entries(settings).forEach(([k, v]) => out.push(`insert into public.settings (key, value) values (${q(k)}, ${q(v)});`));
out.push('');
out.push('commit;');
out.push('');

const target = fileURLToPath(new URL('../seed.sql', import.meta.url));
writeFileSync(target, out.join('\n'));
console.log(`Wrote ${target}: ${serviceList.length} services, ${serviceFaqCount} service FAQs, ${designList.length} designs, ${generalFaqs.length} general FAQs, ${Object.keys(settings).length} settings.`);
